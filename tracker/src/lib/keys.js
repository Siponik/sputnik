/** Настройки → «Клавиши»: 4 группы из HOTKEYS — только клавиши с короткой подписью. «Доска · карточка» идёт в «Доску». */
export function settingsKeys(all = HOTKEYS) {
  const groups = [['Везде', ['Везде']], ['Доска', ['Доска', 'Доска · карточка']], ['Календарь', ['Календарь']], ['Стикеры', ['Стикеры']]];
  return groups.map(([name, from]) => ({
    group: name,
    keys: all.filter((g) => from.includes(g.group)).flatMap((g) => g.keys).filter((k) => k[2]).map(([key, , label]) => [key, label]),
  }));
}
